-- Esquema do banco (Supabase / PostgreSQL).
-- Opcional: por padrão o Hibernate cria as tabelas (DDL_AUTO=update).
-- Para usar este script, execute-o no SQL Editor do Supabase e configure DDL_AUTO=validate.

create table usuario (
    id          bigint generated by default as identity primary key,
    login       varchar(60)  not null unique,
    senha_hash  varchar(255) not null,
    perfil      varchar(20)  not null check (perfil in ('CLIENTE','AGENTE'))
);

create table cliente (
    id          bigint generated by default as identity primary key,
    usuario_id  bigint       not null unique references usuario(id),
    rg          varchar(20)  not null,
    cpf         varchar(11)  not null unique,
    nome        varchar(120) not null,
    endereco    varchar(255) not null,
    profissao   varchar(80)  not null
);

create table rendimento (
    id                    bigint generated by default as identity primary key,
    cliente_id            bigint        not null references cliente(id) on delete cascade,
    entidade_empregadora  varchar(120)  not null,
    valor                 numeric(12,2) not null check (valor >= 0)
);

-- Regra de negócio: no máximo 3 rendimentos por cliente
create or replace function limitar_rendimentos() returns trigger as $$
begin
    if (select count(*) from rendimento where cliente_id = new.cliente_id) >= 3 then
        raise exception 'Um cliente pode ter no máximo 3 rendimentos';
    end if;
    return new;
end;
$$ language plpgsql;

create trigger trg_limitar_rendimentos before insert on rendimento
    for each row execute function limitar_rendimentos();

create table agente (
    id          bigint generated by default as identity primary key,
    usuario_id  bigint       not null unique references usuario(id),
    nome        varchar(120) not null,
    cnpj        varchar(14)  not null unique,
    tipo        varchar(20)  not null check (tipo in ('EMPRESA','BANCO'))
);

create table automovel (
    id                 bigint generated by default as identity primary key,
    matricula          varchar(30) not null unique,
    ano                integer     not null,
    marca              varchar(60) not null,
    modelo             varchar(60) not null,
    placa              varchar(8)  not null unique,
    tipo_proprietario  varchar(20) not null check (tipo_proprietario in ('CLIENTE','EMPRESA','BANCO')),
    proprietario_id    bigint      not null
);

create table contrato_credito (
    id                 bigint generated by default as identity primary key,
    banco_id           bigint        not null references agente(id),
    valor_financiado   numeric(12,2) not null,
    taxa_juros_mensal  numeric(6,4)  not null,
    parcelas           integer       not null check (parcelas >= 1)
);

create table pedido (
    id                    bigint generated by default as identity primary key,
    cliente_id            bigint        not null references cliente(id),
    automovel_id          bigint        not null references automovel(id),
    data_inicio           date          not null,
    data_fim              date          not null,
    valor_total           numeric(12,2) not null,
    status                varchar(20)   not null
                          check (status in ('PENDENTE','APROVADO','REPROVADO','CONTRATADO','CANCELADO')),
    parecer_financeiro    varchar(500),
    agente_avaliador_id   bigint references agente(id),
    contrato_credito_id   bigint references contrato_credito(id),
    data_criacao          timestamp     not null default now()
);

create index idx_pedido_cliente on pedido(cliente_id);
create index idx_pedido_status  on pedido(status);
